-- 1. DISABLE FOREIGN KEYS
EXEC sp_MSforeachtable 'ALTER TABLE ? NOCHECK CONSTRAINT ALL';

-- 2. WIPE OUT EVERY TABLE (Ngoại trừ NguoiDung và HR_Employees)
