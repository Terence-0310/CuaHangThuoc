DELETE FROM HR_Employees WHERE MaND NOT IN (SELECT MaND FROM NguoiDung WHERE TenDangNhap = 'admin') OR MaND IS NULL;

-- 4. RESET IDENTITY (RESEED) CHO CÁC BẢNG ĐÃ XÓA TRẮNG
